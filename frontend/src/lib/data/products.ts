export function getRelatedProducts(productId: string): Product[] {
  const product = getProductById(productId);
  if (!product) return mockProducts.slice(1, 5);
  return mockProducts
    .filter((p) => p.id !== productId && (p.category === product.category || p.brand === product.brand || p.tags.some((t) => product.tags.includes(t))))
    .slice(0, 4);
}

